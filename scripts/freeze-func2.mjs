import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const flag = process.argv.indexOf('--release');
const slug = flag >= 0 ? process.argv[flag + 1] : 'func2r2';
if (!/^func2(?:r[2-9][0-9]*)?$/.test(slug)) throw new Error('invalid release name');
const release = resolve(root, 'releases', slug);
const original = '/Users/sephul/.codex/visualizations/2026/10/14/01a1384f-7fd9-79a2-967a-0568549b46fe/biolab-vesicle-design';
const normative = [
  'p6-structure1-20261024/01-graph-codec.md',
  'p6-structure1-20261024/02-ports-capacity-and-closure.md',
  'rollup1-20261024/01-function-semantics.md',
  'rollup1-20261024/02-function-codec.md',
  'rollup1-20261024/03-function-cases.md',
  'rollup1-20261024/07-semantic-canonical.md',
];
const implementation = [
  'packages/biology/src/graph.mjs', 'packages/biology/src/runtime.mjs',
  'packages/biology/src/evidence.mjs', 'packages/biology/src/canonical.mjs',
  'programs/biolab-kernel/src/graph.rs', 'programs/biolab-kernel/src/runtime.rs',
  'programs/biolab-kernel/Cargo.lock',
];
const sha = data => createHash('sha256').update(data).digest();
const u32 = n => { const b = Buffer.alloc(4); b.writeUInt32LE(n); return b; };
const digestEntries = (domain, entries, prefix = Buffer.alloc(0)) => sha(Buffer.concat([
  Buffer.from(domain, 'ascii'), prefix, u32(entries.length),
  ...entries.flatMap(e => { const name = Buffer.from(e.path, 'utf8'); return [u32(name.length), name,
    u32(e.bytes), Buffer.from(e.sha256, 'hex')]; }),
]));
const fileEntry = path => { const data = readFileSync(resolve(root, path)); return {
  path, bytes: data.length, sha256: sha(data).toString('hex'),
}; };
const manifestPath = resolve(release, 'manifest.json');
if (process.argv.includes('--freeze')) {
  if (existsSync(manifestPath)) throw new Error('release already frozen; use a new release directory for changes');
  mkdirSync(resolve(release, 'normative'), { recursive: true });
  for (const path of normative) {
    const destination = resolve(release, 'normative', path);
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, readFileSync(resolve(original, path)));
  }
  writeFileSync(resolve(release, 'normative/FUNC2.md'), readFileSync(resolve(root, 'docs/FUNC2.md')));
  // Normative identities remain those of the unchanged first FUNC2 rules.
  const rules = [...normative.map(path => `releases/func2/normative/${path}`), 'releases/func2/normative/FUNC2.md'].map(fileEntry);
  const sources = implementation.map(fileEntry);
  const snapshots = sources.map(entry => {
    const path = `releases/${slug}/sources/${entry.path}`, target = resolve(root, path);
    mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, readFileSync(resolve(root, entry.path)));
    return { livePath: entry.path, ...fileEntry(path) };
  });
  const ruleHash = digestEntries('BIORULE2', rules);
  const versions = Buffer.concat([u32(2), u32(1), u32(1), u32(2271)]);
  const validatorHash = digestEntries('BIOVALIDATOR2', sources, Buffer.concat([ruleHash, versions]));
  const manifest = { schema: 1, release: slug.toUpperCase(), productionAdmission: false,
    suite: 2, fixture: 1, load: 1, witnessBytes: 2271,
    ruleHash: ruleHash.toString('hex'), validatorHash: validatorHash.toString('hex'), rules, sources, snapshots };
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  const constant = (name, value) => `pub const ${name}: [u8; 32] = [${[...value].map(n => `0x${n.toString(16).padStart(2, '0')}`).join(', ')}];\n`;
  writeFileSync(resolve(release, 'constants.rs'), '// Generated by scripts/freeze-func2.mjs; semantic release, not a self-hash of the final ELF.\n'
    + constant('RULE_HASH', ruleHash) + constant('VALIDATOR_HASH', validatorHash));
}
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
for (const entry of [...manifest.rules, ...manifest.sources]) {
  const actual = fileEntry(entry.path);
  if (actual.bytes !== entry.bytes || actual.sha256 !== entry.sha256) throw new Error(`frozen source drift: ${entry.path}`);
}
for (const entry of manifest.snapshots ?? []) {
  const actual = fileEntry(entry.path), original = manifest.sources.find(s => s.path === entry.livePath);
  if (actual.sha256 !== entry.sha256 || actual.bytes !== entry.bytes || !original
    || original.sha256 !== entry.sha256 || original.bytes !== entry.bytes) throw new Error(`release snapshot drift: ${entry.path}`);
}
const ruleHash = digestEntries('BIORULE2', manifest.rules);
const versions = Buffer.concat([u32(manifest.suite), u32(manifest.fixture), u32(manifest.load), u32(manifest.witnessBytes)]);
const validatorHash = digestEntries('BIOVALIDATOR2', manifest.sources, Buffer.concat([ruleHash, versions]));
if (ruleHash.toString('hex') !== manifest.ruleHash || validatorHash.toString('hex') !== manifest.validatorHash)
  throw new Error('release manifest digest mismatch');
console.log(JSON.stringify({ release: relative(root, manifestPath), ruleHash: manifest.ruleHash,
  validatorHash: manifest.validatorHash, files: manifest.rules.length + manifest.sources.length,
  productionAdmission: false }));
